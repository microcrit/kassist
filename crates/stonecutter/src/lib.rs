    fn generated_python_modules_are_syntactically_valid() {
        for (name, source) in [
            ("kassist_prelude", crate::python_package_prelude()),
            ("kassist_components", crate::python_component_adapter()),
            ("kassist_krita", crate::python_krita_api()),
            ("kassist_torch", crate::python_torch_api()),
        ] {
            assert!(python_is_available(), "python3 is required for this test");
            compiles(name, source);
        }
    }

    fn python_is_available() -> bool {
        std::process::Command::new("python3")
            .arg("--version")
            .output()
            .is_ok_and(|output| output.status.success())
    }

    fn compiles(name: &str, source: &str) {
        let path = std::env::temp_dir().join(format!(
            "kassist-stonecutter-{name}-{}.py",
            std::process::id()
        ));
        std::fs::write(&path, source).unwrap();
        let output = std::process::Command::new("python3")
            .args(["-m", "py_compile", path.to_str().unwrap()])
            .output()
            .unwrap();
        let _ = std::fs::remove_file(&path);
        assert!(
            output.status.success(),
            "{name} is not valid Python: {}",
            String::from_utf8_lossy(&output.stderr)
        );
    }

