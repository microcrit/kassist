#[derive(Clone, Debug, Eq, PartialEq)]
pub struct PluginId(String);

impl PluginId {
    pub fn new(value: impl Into<String>) -> Result<Self, ValidationError> {
        let value = value.into();
        let segments: Vec<_> = value.split('.').collect();
        ensure!(
            segments.len() >= 2,
            "plugin_id",
            "must contain at least two dot-separated segments"
        );
        ensure!(
            segments.iter().all(|segment| !segment.is_empty()
                && segment.bytes().all(|byte| byte.is_ascii_lowercase()
                    || byte.is_ascii_digit()
                    || byte == b'-')),
            "plugin_id",
            "segments may contain only lowercase ASCII letters, digits, or '-'"
        );
        Ok(Self(value))
    }

    pub fn as_str(&self) -> &str {
        &self.0
    }
}

#[derive(Clone, Debug, Eq, PartialEq)]
pub struct Version {
    major: u16,
    minor: u16,
    patch: u16,
}

impl Version {
    pub const fn new(major: u16, minor: u16, patch: u16) -> Self {
        Self {
            major,
            minor,
            patch,
        }
    }

    pub fn as_string(&self) -> String {
        format!("{}.{}.{}", self.major, self.minor, self.patch)
    }
}

#[derive(Clone, Debug, Eq, PartialEq)]
pub struct PluginManifest {
    id: PluginId,
    name: String,
    version: Version,
    minimum_krita_version: Version,
}

impl PluginManifest {
    pub fn new(
        id: PluginId,
        name: impl Into<String>,
        version: Version,
        minimum_krita_version: Version,
    ) -> Result<Self, ValidationError> {
        let name = name.into();
        ensure!(!name.trim().is_empty(), "name", "must not be empty");
        Ok(Self {
            id,
            name,
            version,
            minimum_krita_version,
        })
    }

    pub fn id(&self) -> &PluginId {
        &self.id
    }

    pub fn name(&self) -> &str {
        &self.name
    }

    pub fn version(&self) -> &Version {
        &self.version
    }

    pub fn minimum_krita_version(&self) -> &Version {
        &self.minimum_krita_version
    }

    pub fn licensing<'a, Server: LicenseServer>(
        &'a self,
        server: &'a Server,
    ) -> LicenseClient<'a, Server> {
        LicenseClient {
            product: &self.id,
            server,
        }
    }
}

