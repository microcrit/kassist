#[derive(Clone, Debug, Eq, PartialEq)]
pub struct ActivationRequest {
    pub product: PluginId,
    pub license_key: LicenseKey,
    pub installation: InstallationId,
}

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum LicenseState {
    Active,
    Expired,
    Revoked,
    Invalid,
}

#[derive(Clone, Debug, Eq, PartialEq)]
pub struct LicenseStatus {
    state: LicenseState,
    expires_at: Option<i64>,
}

impl LicenseStatus {
    pub const fn new(state: LicenseState, expires_at: Option<i64>) -> Self {
        Self { state, expires_at }
    }

    pub const fn state(&self) -> LicenseState {
        self.state
    }

    pub const fn expires_at(&self) -> Option<i64> {
        self.expires_at
    }

    pub const fn is_active(&self) -> bool {
        matches!(self.state, LicenseState::Active)
    }
}

pub trait LicenseServer {
    fn activate(&self, request: ActivationRequest) -> Result<LicenseStatus, LicenseError>;
}

#[derive(Clone, Debug, Eq, PartialEq)]
pub enum LicenseError {
    Transport(String),
    Rejected(LicenseState),
}

#[cfg(feature = "http-client")]
pub struct HttpLicenseServer {
    base_url: String,
    client: reqwest::blocking::Client,
}

#[cfg(feature = "http-client")]
impl HttpLicenseServer {
    pub const PRODUCTION_URL: &'static str = "https://ls.hellings.cc";

    pub fn production() -> Self {
        Self::new(Self::PRODUCTION_URL)
    }

    pub fn new(base_url: impl Into<String>) -> Self {
        Self {
            base_url: base_url.into().trim_end_matches('/').to_owned(),
            client: reqwest::blocking::Client::new(),
        }
    }

    fn activation_url(&self) -> String {
        format!("{}/v1/activations", self.base_url)
    }
}

#[cfg(feature = "http-client")]
impl LicenseServer for HttpLicenseServer {
    fn activate(&self, request: ActivationRequest) -> Result<LicenseStatus, LicenseError> {
        let response = self
            .client
            .post(self.activation_url())
            .json(&HttpActivationRequest {
                product: request.product.as_str(),
                license_key: request.license_key.as_str(),
                installation: request.installation.as_str(),
            })
            .send()
            .map_err(|error| LicenseError::Transport(error.to_string()))?;
        if !response.status().is_success() {
            return Err(LicenseError::Transport(format!(
                "licensing server returned {}",
                response.status()
            )));
        }
        let response: HttpActivationResponse = response
            .json()
            .map_err(|error| LicenseError::Transport(error.to_string()))?;
        let state = match response.state.as_str() {
            "active" => LicenseState::Active,
            "expired" => LicenseState::Expired,
            "revoked" => LicenseState::Revoked,
            _ => LicenseState::Invalid,
        };
        Ok(LicenseStatus::new(state, response.expires_at))
    }
}

#[cfg(feature = "http-client")]
#[derive(serde::Serialize)]
struct HttpActivationRequest<'a> {
    product: &'a str,
    license_key: &'a str,
    installation: &'a str,
}

#[cfg(feature = "http-client")]
#[derive(serde::Deserialize)]
struct HttpActivationResponse {
    state: String,
    expires_at: Option<i64>,
}

pub struct LicenseClient<'a, Server> {
    product: &'a PluginId,
    server: &'a Server,
}

impl<Server: LicenseServer> LicenseClient<'_, Server> {
    pub fn activate(
        &self,
        license_key: LicenseKey,
        installation: InstallationId,
    ) -> Result<LicenseStatus, LicenseError> {
        let status = self.server.activate(ActivationRequest {
            product: self.product.clone(),
            license_key,
            installation,
        })?;
        if status.is_active() {
            Ok(status)
        } else {
            Err(LicenseError::Rejected(status.state()))
        }
    }
}

pub trait Plugin {
    fn manifest(&self) -> &PluginManifest;

    fn panel(&self) -> &Panel;

    fn invoke(&mut self, action: &str) -> Result<(), PluginError>;

    fn activate<Server: LicenseServer>(
        &self,
        server: &Server,
        license_key: LicenseKey,
        installation: InstallationId,
    ) -> Result<LicenseStatus, LicenseError> {
        self.manifest()
            .licensing(server)
            .activate(license_key, installation)
    }
}

